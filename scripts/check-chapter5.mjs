import fs from 'node:fs';
import assert from 'node:assert/strict';
const pages = Array.from({length:9},(_,i)=>({page:i+42,text:fs.readFileSync('docs/psr2021-chapter5/page-'+(i+42)+'.md','utf8')}));
const expected=['050101','050102','050103','050104','050201','050202','050203','050204','050205','050206','050207','050301','050401','050402','050403','050404','050405','050406','050501','050601','050701','050702','050703'];
assert.deepEqual(pages.map(p=>p.page),[42,43,44,45,46,47,48,49,50]);
const joined=pages.map(p=>p.text).join('\n\n');
const found=Array.from(joined.matchAll(/^\s*(050\d{3})\s*(?:[-.:]|\()/gm),m=>m[1]);
assert.deepEqual(found,expected,'Chapter 5 rule numbering and ordering');
assert.equal(new Set(found).size,23);
for(const p of pages)assert.ok(p.text.length>300,'Missing page '+p.page);
assert.match(pages[0].text,/050103/);
assert.match(pages[1].text,/he departs, whether/);
assert.match(pages[2].text,/Reporting Officer shall be/);
assert.match(pages[3].text,/050401/);
assert.match(pages[4].text,/until Annual Performance Goals/);
assert.match(pages[5].text,/with this responsibility/);
assert.match(pages[6].text,/050406/);
assert.match(pages[7].text,/050601/);
assert.match(pages[8].text,/050703/);
assert.match(pages[3].text,/ii\.[\s\S]*iv\./,'printed 050301 item-number skip retained');
assert.equal((pages[7].text.match(/\(iv\)/g)||[]).length,2,'printed repeated iv retained');
console.log('PASS Chapter 5: 9 original PDF pages, 23 distinct ordered rules, cross-page continuations and numbering anomalies');
